def _place(name: str, kind: str = "gu") -> dict:
    return {"place": {"name": name, "kind": kind}, "spatial_mode": "auto"}


def _plan(**kwargs) -> dict:
    data = {
        "version": "1.0",
        "query_kind": "list",
        "entity": "building",
        "scope": None,
        "filters": [],
        "select": [],
        "aggregations": [],
        "group_by": [],
        "order_by": [],
        "limit": None,
        "spatial_relations": [],
        "requires_clarification": False,
        "ambiguities": [],
        "assumptions": [],
        "unsupported_reason": None,
        "model_confidence": 1.0,
    }
    data.update(kwargs)
    return data


